import assert from "node:assert/strict";
import { classifyCalibrationFailure, completedHumanReview, contentHash, freezeCopy, qualityEfficiency, humanDimensions } from "./calibration_support";
const original = { evidence: { signals: ["observed evidence"] }, profile: { axes: ["a", "b"] } };
const frozen = freezeCopy(original);
assert.throws(() => frozen.evidence.signals.push("contamination"));
original.profile.axes.push("later upstream mutation");
assert.deepEqual(frozen.profile.axes, ["a", "b"]);
assert.notEqual(contentHash(original), contentHash(frozen));
assert.equal(contentHash(frozen), contentHash(freezeCopy(frozen)));
assert.equal(classifyCalibrationFailure({ error: "PIPELINE_TIMEOUT" }), "TIMEOUT");
assert.equal(classifyCalibrationFailure({ errorCategory: "RATE_LIMITED", taskType: "EXPRESSION_VERIFICATION" }), "PROVIDER_RATE_LIMIT");
assert.equal(classifyCalibrationFailure({ error: "GENERATION_EXHAUSTED" }), "CREATIVE_ZERO");
for (const [taskType, category] of [["PROFILE_REASONING", "PROFILE_API_FAILURE"], ["COMPOSITION_INFERENCE", "COMPOSITION_FAILURE"], ["EXPRESSION_INTENT", "INTENT_API_FAILURE"], ["SLOGAN_GENERATION", "GENERATION_API_FAILURE"], ["SEMANTIC_VERIFICATION", "SEMANTIC_VERIFIER_FAILURE"], ["EXPRESSION_VERIFICATION", "EXPRESSION_VERIFIER_FAILURE"]]) assert.equal(classifyCalibrationFailure({ taskType }), category);
assert.equal(classifyCalibrationFailure({ taskType: "PROFILE_REASONING", errorCategory: "STRUCTURAL_FAILURE" }), "PROFILE_FORMAT_FAILURE");
assert.equal(classifyCalibrationFailure({ taskType: "EXPRESSION_INTENT", error: "VERIFIER_INCOMPLETE" }), "INTENT_FORMAT_FAILURE");
const review = { humanScore: Object.fromEntries(humanDimensions.map(key => [key, 3])), wouldChooseForShirt: "YES", expressionJudgment: "HUMAN EXPRESSION", overallPreference: "A" };
assert.equal(completedHumanReview(review), true);
assert.equal(completedHumanReview({ ...review, wouldChooseForShirt: null }), false);
assert.equal(completedHumanReview({ ...review, humanScore: { ...review.humanScore, nicheTruth: 0 } }), false);
assert.equal(completedHumanReview({ ...review, expressionJudgment: null }), false);
assert.equal(qualityEfficiency(null, 0.5, 10, 0).gainPerAddedDollar, null);
assert.equal(qualityEfficiency(1, 0, 0, 0).riskAdjustedGain, null);
assert.equal(qualityEfficiency(1, 0.5, 10, 0.2).riskAdjustedGain, 0.16);
console.log("STAGE CALIBRATION: PASS");
